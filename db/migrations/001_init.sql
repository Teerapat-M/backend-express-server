select setval(
  pg_get_serial_sequence('public.statuses', 'id'),
  coalesce((select max(id) from public.statuses), 1)
);

select setval(
  pg_get_serial_sequence('public.categories', 'id'),
  coalesce((select max(id) from public.categories), 1)
);

