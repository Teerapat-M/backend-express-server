-- ---------------------------------------------------------------------------
-- Storage: bucket used by apps/postRoutes.mjs
--   bucketName = "my-personal-blog"
--   filePath   = posts/${Date.now()}_${originalname}
-- Uploads use SUPABASE_ANON_KEY without attaching the user JWT, so INSERT
-- must be allowed for anon (otherwise create-post image upload fails).
-- Public bucket: getPublicUrl works without a SELECT policy on objects.
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'my-personal-blog',
  'my-personal-blog',
  true,
  5242880, -- 5MB, matches utils/postValidation.mjs MAX_IMAGE_SIZE
  array['image/jpeg', 'image/png', 'image/gif', 'image/webp']
)
on conflict (id) do update
set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "my-personal-blog anon upload" on storage.objects;
create policy "my-personal-blog anon upload"
  on storage.objects
  for insert
  to anon, authenticated
  with check (
    bucket_id = 'my-personal-blog'
    and (storage.foldername(name))[1] in ('posts', 'profiles')
  );
