-- Reverse-engineered schema for a fresh, empty Supabase Postgres project.
-- Paste this into the Supabase SQL Editor. Do not apply from CI or to a live
-- database that already has data.
--
-- Source of truth: this repo's SQL (pg queries) plus the sibling TechUp
-- personal-blog template this backend was copied from
-- (Teerapat-M/blog-post-project-fullstack) and Teerapat-M/my-profile.
-- Columns / tables marked "guessed" were not named in this repo's queries.

-- ---------------------------------------------------------------------------
-- Extensions
-- ---------------------------------------------------------------------------
create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- Lookup tables
-- ---------------------------------------------------------------------------

-- categories.id is a number: this backend validates category_id with Number()
-- and joins posts.category_id = categories.id.
create table if not exists public.categories (
  id integer generated by default as identity primary key,
  name text not null,
  -- guessed: unique so admin category names stay distinct (frontend also
  -- rejects duplicate names).
  constraint categories_name_key unique (name)
);

-- statuses.id = 2 is "published" in the course template
-- (WHERE statuses.id = 2). my-profile maps draft=1, published=2.
create table if not exists public.statuses (
  id integer generated by default as identity primary key,
  status text not null,
  constraint statuses_status_key unique (status)
);

-- ---------------------------------------------------------------------------
-- Users (app profile row; auth lives in auth.users)
-- ---------------------------------------------------------------------------

-- users.id is the Supabase Auth user UUID (auth.signUp -> data.user.id).
create table if not exists public.users (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null,
  name text not null,
  role text not null default 'user',
  -- guessed: course template SELECT users.profile_pic / UPDATE profile_pic.
  -- this backend never reads or writes it.
  profile_pic text,
  -- guessed: created_at is unused by this backend.
  created_at timestamptz not null default now(),
  constraint users_username_key unique (username),
  constraint users_role_check check (role in ('user', 'admin'))
);

-- ---------------------------------------------------------------------------
-- Posts
-- ---------------------------------------------------------------------------

create table if not exists public.posts (
  id integer generated by default as identity primary key,
  title text not null,
  image text not null,
  category_id integer not null references public.categories (id),
  description text not null,
  content text not null,
  status_id integer not null references public.statuses (id),
  -- INSERT in apps/postRoutes.mjs omits date, so it needs a default.
  -- routes/assignments.mjs sends new Date() into this column.
  -- guessed type: timestamptz (pg accepts JS Date).
  date timestamptz not null default now(),
  -- SELECT posts.likes_count; INSERT omits it, so it needs a default.
  likes_count integer not null default 0,
  constraint posts_likes_count_nonnegative check (likes_count >= 0)
);

create index if not exists posts_date_desc_idx on public.posts (date desc);
create index if not exists posts_category_id_idx on public.posts (category_id);
create index if not exists posts_status_id_idx on public.posts (status_id);

-- ---------------------------------------------------------------------------
-- Comments + likes
-- Guessed tables: this backend has no comment/like routes. They existed on
-- the original TechUp personal-blog schema (blog-post-project-fullstack
-- postRouter) and my-profile still has comment/like UI.
-- ---------------------------------------------------------------------------

create table if not exists public.comments (
  id integer generated by default as identity primary key,
  post_id integer not null references public.posts (id) on delete cascade,
  user_id uuid not null references public.users (id) on delete cascade,
  comment_text text not null,
  -- INSERT omits created_at; course template ORDER BY comments.created_at DESC.
  created_at timestamptz not null default now(),
  -- guessed: course template rejects empty / >500 character comments.
  constraint comments_comment_text_len check (
    char_length(btrim(comment_text)) > 0
    and char_length(comment_text) <= 500
  )
);

create index if not exists comments_post_id_idx on public.comments (post_id);
create index if not exists comments_user_id_idx on public.comments (user_id);

create table if not exists public.likes (
  post_id integer not null references public.posts (id) on delete cascade,
  user_id uuid not null references public.users (id) on delete cascade,
  -- guessed: unused by queries; useful for ordering.
  created_at timestamptz not null default now(),
  -- guessed: one like per user per post (course DELETE WHERE post_id AND user_id).
  primary key (post_id, user_id)
);

create index if not exists likes_user_id_idx on public.likes (user_id);

-- Keep posts.likes_count in sync if likes rows are written later.
-- guessed trigger: this backend never writes likes, but it reads likes_count.
-- SECURITY DEFINER lives in a private schema so it is not reachable via the
-- Data API (public security-definer functions are a Supabase footgun).
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create or replace function private.sync_post_likes_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.posts
    set likes_count = likes_count + 1
    where id = new.post_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.posts
    set likes_count = greatest(likes_count - 1, 0)
    where id = old.post_id;
    return old;
  end if;
  return null;
end;
$$;

drop trigger if exists trg_likes_sync_count on public.likes;
create trigger trg_likes_sync_count
after insert or delete on public.likes
for each row
execute function private.sync_post_likes_count();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- Express talks to Postgres as the CONNECTION_STRING role (usually postgres),
-- which bypasses RLS. RLS still matters because the Data API (anon /
-- authenticated) is exposed on every Supabase project.
-- ---------------------------------------------------------------------------

alter table public.categories enable row level security;
alter table public.statuses enable row level security;
alter table public.posts enable row level security;
alter table public.users enable row level security;
alter table public.comments enable row level security;
alter table public.likes enable row level security;

drop policy if exists categories_public_read on public.categories;
create policy categories_public_read
  on public.categories
  for select
  to anon, authenticated
  using (true);

drop policy if exists statuses_public_read on public.statuses;
create policy statuses_public_read
  on public.statuses
  for select
  to anon, authenticated
  using (true);

drop policy if exists posts_public_read on public.posts;
create policy posts_public_read
  on public.posts
  for select
  to anon, authenticated
  using (true);

-- users: no anon/authenticated policies. Profile rows stay Express-only
-- (postgres role). Do not expose username/role through the Data API.

drop policy if exists comments_public_read on public.comments;
create policy comments_public_read
  on public.comments
  for select
  to anon, authenticated
  using (true);

drop policy if exists comments_authenticated_insert on public.comments;
create policy comments_authenticated_insert
  on public.comments
  for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists likes_public_read on public.likes;
create policy likes_public_read
  on public.likes
  for select
  to anon, authenticated
  using (true);

drop policy if exists likes_authenticated_insert on public.likes;
create policy likes_authenticated_insert
  on public.likes
  for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists likes_authenticated_delete on public.likes;
create policy likes_authenticated_delete
  on public.likes
  for delete
  to authenticated
  using (user_id = auth.uid());

